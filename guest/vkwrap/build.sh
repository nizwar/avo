#!/usr/bin/env bash
# Builds the wrapping vulkan.ranchu.so with the Android NDK (no Gradle) and
# writes it into the daemon as Base64
# (host/AvoKit/Sources/AvoDaemonCore/VulkanWrapperHelper.swift).
#
#   vulkan.ranchu.so  a Vulkan HAL driver that loads the real one and runs the
#                     gfxstream sync layer (guest/gfxsync) over it, so none of
#                     that layer has to sit in /data/local/debug where a
#                     packer such as ijiami kills the app over it
#                     (src/vk_wrap.c says how; the layer is reused unchanged).
#
# GuestVulkanWrapper installs it with the real driver beside it, in a
# directory bind-mounted over /apex/com.google.cf.vulkan/lib64/hw.
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
GFXSYNC="$ROOT/guest/gfxsync/src"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
NDK="${ANDROID_NDK_HOME:-$SDK/ndk/$(ls "$SDK/ndk" | sort -V | tail -1)}"
BIN="$NDK/toolchains/llvm/prebuilt/$(ls "$NDK/toolchains/llvm/prebuilt" | head -1)/bin"
# Android 11 is the oldest Avo boots; the wrapper uses libc, liblog and dl.
CC="$BIN/aarch64-linux-android30-clang"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"

# No build ID and no paths: the same sources and NDK give the same bytes, so
# the daemon replaces the guest's copy only when something changed.
# 16 KiB pages work on 4 KiB and 16 KiB kernels. -Bsymbolic: the wrapper's
# calls to the layer's vkGetInstanceProcAddr/vkGetDeviceProcAddr stay its own,
# whatever else in the process exports those names.
FLAGS=(-std=c11 -O2 -fPIC -shared -fvisibility=hidden -Wall -Wextra -Werror
       -I"$GFXSYNC"
       -ffile-prefix-map="$HERE"=. -ffile-prefix-map="$GFXSYNC"=.
       -Wl,--build-id=none -Wl,-z,max-page-size=16384 -Wl,--no-undefined -Wl,-Bsymbolic)
LIB="vulkan.ranchu.so"
(cd "$HERE" && "$CC" "${FLAGS[@]}" -o "$OUT/$LIB" src/vk_wrap.c "$GFXSYNC/vk_layer.c" "$GFXSYNC/frag_outputs.c" -llog)
"$BIN/llvm-strip" --strip-unneeded "$OUT/$LIB"

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/VulkanWrapperHelper.swift"
{
  echo "// Generated by guest/vkwrap/build.sh from guest/vkwrap/src and guest/gfxsync/src. Do not edit."
  echo
  echo "/// Avo's wrapping Vulkan driver, which HostAgent installs over the gfxstream driver (GuestVulkanWrapper)."
  echo "enum VulkanWrapperHelper {"
  echo "    /// $LIB"
  echo "    static let driver = \"$(base64 < "$OUT/$LIB" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $(wc -c < "$OUT/$LIB" | tr -d ' ') bytes of wrapper -> $SWIFT"
