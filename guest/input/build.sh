#!/usr/bin/env bash
# Build the Android input service and embed it in the daemon.
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-36/android.jar"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"/{classes,dex}

"$BT/aapt2" compile --dir "$HERE/res" -o "$OUT/resources.zip"
"$BT/aapt2" link -I "$JAR" --manifest "$HERE/AndroidManifest.xml" -o "$OUT/unsigned.apk" "$OUT/resources.zip"
javac --release 17 -nowarn -cp "$JAR" -d "$OUT/classes" "$HERE"/src/com/avodroid/input/*.java
"$BT/d8" --release --min-api 34 --lib "$JAR" --output "$OUT/dex" "$OUT"/classes/com/avodroid/input/*.class
TZ=UTC touch -t 198101010000 "$OUT/dex/classes.dex"
(cd "$OUT/dex" && TZ=UTC zip -q -X -j "$OUT/unsigned.apk" classes.dex)
"$BT/zipalign" -f 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"
# Android requires the same signing key for APK updates.
KEY="$HERE/input.keystore"
SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/AvoInputHelper.swift"
if [[ ! -f "$KEY" && -f "$SWIFT" ]]; then
    # A clean checkout can rebuild the release without its private signing key.
    # Reuse the signed artifact only when every compiled resource and classes.dex match.
    if python3 - "$SWIFT" "$OUT/aligned.apk" "$OUT/AvoInput.apk" <<'PY'
import base64, io, pathlib, re, sys, zipfile

source, unsigned, output = map(pathlib.Path, sys.argv[1:])
payload = base64.b64decode(re.search(r'static let apk = "([^"]+)"', source.read_text())[1])
with zipfile.ZipFile(unsigned) as built, zipfile.ZipFile(io.BytesIO(payload)) as signed:
    files = {name for name in signed.namelist() if not name.startswith("META-INF/")}
    if files != set(built.namelist()) or any(built.read(name) != signed.read(name) for name in files):
        sys.exit(1)
output.write_bytes(payload)
PY
    then
        "$BT/apksigner" verify "$OUT/AvoInput.apk"
        exit 0
    fi
fi
if [[ ! -f "$KEY" ]]; then
    (umask 077 && keytool -genkeypair -storetype PKCS12 -keystore "$KEY" -storepass android \
        -keypass android -alias input -keyalg RSA -keysize 2048 -validity 10000 -dname 'CN=Avo Input' >/dev/null)
fi
"$BT/apksigner" sign --ks "$KEY" --ks-pass pass:android --key-pass pass:android \
    --out "$OUT/AvoInput.apk" "$OUT/aligned.apk"
"$BT/apksigner" verify "$OUT/AvoInput.apk"

{
    echo '// Generated by guest/input/build.sh from guest/input. Do not edit.'
    echo
    echo 'enum AvoInputHelper {'
    echo "    static let apk = \"$(base64 < "$OUT/AvoInput.apk" | tr -d '\n')\""
    echo '}'
} > "$SWIFT"
