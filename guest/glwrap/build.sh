#!/usr/bin/env bash
# Builds the wrapping libGLESv2_angle.so with the Android NDK (no Gradle) and
# writes it into the daemon as Base64
# (host/AvoKit/Sources/AvoDaemonCore/GLESWrapperHelper.swift).
#
#   libGLESv2_angle.so  ANGLE's GLES library as libEGL loads it, answering an
#                       app's own glGetString with the device profile's GPU
#                       (guest/gpuprofile/src/gles_profile.h) and handing
#                       everything else to the real library, which it needs
#                       (DT_NEEDED libGLESv2_angle.avoreal.so). No GLES layer,
#                       so nothing sits in /data/local/debug and Android needs
#                       no ro.debuggable=1 (src/gl_wrap.c says how).
#
# GuestGLESWrapper installs it with the real library beside it in
# /system/lib64 and bind-mounts it over /system/lib64/libGLESv2_angle.so.
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
GPUPROFILE="$ROOT/guest/gpuprofile/src"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
NDK="${ANDROID_NDK_HOME:-$SDK/ndk/$(ls "$SDK/ndk" | sort -V | tail -1)}"
BIN="$NDK/toolchains/llvm/prebuilt/$(ls "$NDK/toolchains/llvm/prebuilt" | head -1)/bin"
# Android 11 is the oldest Avo boots; the wrapper uses libc and dl.
CC="$BIN/aarch64-linux-android30-clang"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT/stub"

# The real library's name for the linker: an empty stand-in with its SONAME,
# so the wrapper needs it by that name and loads it from /system/lib64.
REAL="libGLESv2_angle.avoreal.so"
echo "" > "$OUT/stub/empty.c"
"$CC" -shared -fPIC -Wl,-soname,"$REAL" -o "$OUT/stub/$REAL" "$OUT/stub/empty.c"

# No build ID and no paths: the same sources and NDK give the same bytes, so
# the daemon replaces the guest's copy only when something changed.
# 16 KiB pages work on 4 KiB and 16 KiB kernels. -Bsymbolic: the wrapper's
# own calls stay its own. The SONAME is the real library's, which
# libEGL_angle.so and libGLESv1_CM_angle.so need by that name.
FLAGS=(-std=c11 -O2 -fPIC -shared -fvisibility=hidden -Wall -Wextra -Werror
       -I"$GPUPROFILE"
       -ffile-prefix-map="$HERE"=. -ffile-prefix-map="$GPUPROFILE"=.
       -Wl,--build-id=none -Wl,-z,max-page-size=16384 -Wl,--no-undefined -Wl,-Bsymbolic
       -Wl,-soname,libGLESv2_angle.so -Wl,--no-as-needed)
LIB="libGLESv2_angle.so"
(cd "$HERE" && "$CC" "${FLAGS[@]}" -o "$OUT/$LIB" src/gl_wrap.c -L"$OUT/stub" -l:"$REAL" -ldl)
"$BIN/llvm-strip" --strip-unneeded "$OUT/$LIB"

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/GLESWrapperHelper.swift"
{
  echo "// Generated by guest/glwrap/build.sh from guest/glwrap/src and guest/gpuprofile/src. Do not edit."
  echo
  echo "/// Avo's wrapping ANGLE GLES library, which HostAgent installs over ANGLE's (GuestGLESWrapper)."
  echo "enum GLESWrapperHelper {"
  echo "    /// $LIB"
  echo "    static let library = \"$(base64 < "$OUT/$LIB" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $(wc -c < "$OUT/$LIB" | tr -d ' ') bytes of wrapper -> $SWIFT"
