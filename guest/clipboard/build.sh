#!/usr/bin/env bash
# Builds avo-clipboard.jar (a dex jar run with app_process: the clipboard bridge,
# `appinfo`, the notifications' `dismiss`, `actions` and `act`, and `media`) and writes it into the daemon as Base64
# (host/AvoKit/Sources/AvoDaemonCore/ClipboardHelper.swift).
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
API=36
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-$API/android.jar"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"/{classes,dex}

javac --release 17 -nowarn -cp "$JAR" -d "$OUT/classes" $(find "$HERE/src" -name '*.java')
"$BT/d8" --release --min-api 30 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')
(cd "$OUT/dex" && zip -q -X "$OUT/avo-clipboard.jar" classes.dex)

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/ClipboardHelper.swift"
{
  echo "// Generated by guest/clipboard/build.sh from guest/clipboard/src. Do not edit."
  echo
  echo "/// avo-clipboard.jar: the clipboard bridge, app-info, notification (dismiss, buttons) and Now Playing helper HostAgent runs with app_process."
  echo "enum ClipboardHelper {"
  echo "    static let jar = \"$(base64 < "$OUT/avo-clipboard.jar" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $OUT/avo-clipboard.jar ($(wc -c < "$OUT/avo-clipboard.jar" | tr -d ' ') bytes) -> $SWIFT"
