#!/usr/bin/env bash
# Builds build/AvoWidgets.apk (Avo Widgets: Android apps' home screen widgets
# on the Mac) with the Android SDK, no Gradle, and writes
# it into the daemon as Base64 (host/AvoKit/Sources/AvoDaemonCore/WidgetsHelper.swift),
# which HostAgent installs when Android's copy differs.
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
#
# debug.p12 signs it. It is kept with the sources (and named so `*.keystore`
# in .gitignore leaves it in) so every build has the same signature and
# installs over the last; it guards nothing, its password is "android".
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
API=36
BT="$SDK/build-tools/$(ls "$SDK/build-tools" | sort -V | tail -1)"
JAR="$SDK/platforms/android-$API/android.jar"
# Without that platform, the newest one there is (only API 34 calls are used).
[[ -f "$JAR" ]] || JAR="$(ls -d "$SDK"/platforms/android-* | sort -V | tail -1)/android.jar"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"/{res,classes,dex}

"$BT/aapt2" compile --dir "$HERE/res" -o "$OUT/res/compiled.zip"
"$BT/aapt2" link -I "$JAR" --manifest "$HERE/AndroidManifest.xml" -o "$OUT/unsigned.apk" "$OUT/res/compiled.zip"
javac --release 17 -nowarn -cp "$JAR" -d "$OUT/classes" $(find "$HERE/src" -name '*.java')
"$BT/d8" --release --min-api 34 --lib "$JAR" --output "$OUT/dex" $(find "$OUT/classes" -name '*.class')
# A fixed date and no extra fields: the same sources give the same APK, so the
# daemon reinstalls only when something changed.
TZ=UTC touch -t 198101010000 "$OUT/dex/classes.dex"
(cd "$OUT/dex" && TZ=UTC zip -q -X -j "$OUT/unsigned.apk" classes.dex)
"$BT/zipalign" -f 4 "$OUT/unsigned.apk" "$OUT/aligned.apk"

KEY="$HERE/debug.p12"
if [[ ! -f "$KEY" ]]; then
  keytool -genkeypair -storetype PKCS12 -keystore "$KEY" -storepass android -keypass android -alias debug \
    -keyalg RSA -keysize 2048 -validity 10000 -dname "CN=Avo Widgets Debug" >/dev/null 2>&1
fi
"$BT/apksigner" sign --ks "$KEY" --ks-type PKCS12 --ks-pass pass:android --key-pass pass:android \
  --out "$OUT/AvoWidgets.apk" "$OUT/aligned.apk"
"$BT/apksigner" verify "$OUT/AvoWidgets.apk"

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/WidgetsHelper.swift"
{
  echo "// Generated by guest/widgets/build.sh from guest/widgets. Do not edit."
  echo
  echo "/// AvoWidgets.apk: Android apps' widgets on the Mac (HostAgent's Widgets)."
  echo "enum WidgetsHelper {"
  echo "    static let apk = \"$(base64 < "$OUT/AvoWidgets.apk" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $OUT/AvoWidgets.apk ($(wc -c < "$OUT/AvoWidgets.apk" | tr -d ' ') bytes) -> $SWIFT"
