#!/usr/bin/env bash
# Builds VK_LAYER_AVO_gfxstream_sync with the Android NDK (no Gradle) and
# writes it into the daemon as Base64
# (host/AvoKit/Sources/AvoDaemonCore/GfxstreamSyncHelper.swift).
#
#   libVkLayer_avo_gfxstream_sync.so  keeps the guest gfxstream Vulkan driver
#                                     from deadlocking, splits fragment
#                                     output arrays for MoltenVK, gives
#                                     ANGLE VK_EXT_provoking_vertex, and
#                                     turns on its exposeES32ForTesting so
#                                     apps get OpenGL ES 3.2
#                                     (src/vk_layer.c says how)
#
# HostAgent installs it in /data/local/debug/vulkan in GPU mode and lists it
# in debug.vulkan.layer.9 (GuestGfxstreamSync). test/run.sh tests the shader
# rewrite on the Mac against the emulator's MoltenVK.
#
#   ANDROID_HOME=~/Library/Android/sdk ./build.sh
set -euo pipefail

HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../.." && pwd)"
SDK="${ANDROID_HOME:-$HOME/Library/Android/sdk}"
NDK="${ANDROID_NDK_HOME:-$SDK/ndk/$(ls "$SDK/ndk" | sort -V | tail -1)}"
BIN="$NDK/toolchains/llvm/prebuilt/$(ls "$NDK/toolchains/llvm/prebuilt" | head -1)/bin"
# Android 11 is the oldest Avo boots; the layer only uses libc and liblog.
CC="$BIN/aarch64-linux-android30-clang"
OUT="$HERE/build"
rm -rf "$OUT"
mkdir -p "$OUT"

# No build ID and no paths: the same sources and NDK give the same bytes, so
# the daemon replaces Android's copy only when something changed.
# 16 KiB pages work on 4 KiB and 16 KiB kernels.
FLAGS=(-std=c11 -O2 -fPIC -shared -fvisibility=hidden -Wall -Wextra -Werror
       -ffile-prefix-map="$HERE"=. -Wl,--build-id=none -Wl,-z,max-page-size=16384 -Wl,--no-undefined)
LIB="libVkLayer_avo_gfxstream_sync.so"
(cd "$HERE" && "$CC" "${FLAGS[@]}" -o "$OUT/$LIB" src/vk_layer.c src/frag_outputs.c -llog)
"$BIN/llvm-strip" --strip-unneeded "$OUT/$LIB"

SWIFT="$ROOT/host/AvoKit/Sources/AvoDaemonCore/GfxstreamSyncHelper.swift"
{
  echo "// Generated by guest/gfxsync/build.sh from guest/gfxsync/src. Do not edit."
  echo
  echo "/// Avo's gfxstream sync layer, which HostAgent installs in /data/local/debug/vulkan (GuestGfxstreamSync)."
  echo "enum GfxstreamSyncHelper {"
  echo "    /// $LIB"
  echo "    static let vulkan = \"$(base64 < "$OUT/$LIB" | tr -d '\n')\""
  echo "}"
} > "$SWIFT"
echo "built $(wc -c < "$OUT/$LIB" | tr -d ' ') bytes of layer -> $SWIFT"
